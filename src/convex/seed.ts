function chapterVariants(template: ChapterTemplate, cities: string[]): SeedOpp[] {
  return cities.map((city) => ({
    title: template.title(city),
    subtitle: template.short(city),
    provider: template.provider,
    category: template.category,
    subFields: template.subFields,
    country: template.country,
    location: city,
    remote: template.remote,
    eligibility: template.eligibility,
    grades: template.grades,
    cost: template.cost,
    stipend: null,
    stipendText: template.stipendText,
    deadlineDays: template.deadlineDays + Math.floor(Math.random() * 8),
    duration: template.duration,
    emoji: template.emoji,
    colors: template.colors,
    tags: template.tags,
    short: template.short(city),
    desc: template.desc(city),
    url: `https://antren.app/program/${template.category}/${city.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`,
    docs: ["Online application"],
    method: "Online application",
  }));
}

function buildSeed(): SeedOpp[] {
  const out: SeedOpp[] = [...S];

  // Local US chapters
  for (const t of CHAPTER_TEMPLATES) {
    const cities = CITIES["United States"];
    const shuffled = [...cities].sort(() => Math.random() - 0.5);
    out.push(...chapterVariants(t, shuffled.slice(0, 8)));
  }

  // Global chapter programs across many countries
  const allCountries = Object.keys(CITIES).filter((c) => c !== "United States");
  for (const t of GLOBAL_CHAPTERS) {
    const countries = [...allCountries].sort(() => Math.random() - 0.5).slice(0, 10);
    for (const country of countries) {
      const city = CITIES[country][Math.floor(Math.random() * CITIES[country].length)];
      out.push(
        ...chapterVariants(
          {
            ...t,
            country,
            title: (c) => t.title(country),
          },
          [city],
        ),
      );
    }
  }

  // A handful of city-chapter research/internship variants in emerging hubs
  const hubTemplate: ChapterTemplate = {
    title: (c) => `Young Founders Fellowship — ${c}`,
    provider: "Antren Fellowship Network",
    category: "fellowships",
    subFields: ["Founding", "MVP", "Pitching", "Accelerators"],
    country: "Global",
    remote: true,
    eligibility: "Ages 16–22, early-stage idea required",
    grades: ["11", "12", "college"],
    cost: 0,
    stipendText: "Up to $500 micro-grants",
    deadlineDays: G(33),
    duration: "12 weeks",
    emoji: "🚀",
    colors: ["#7C3AED", "#1E1B4B"],
    tags: ["startup", "fellowship", "global"],
    short: (c) => `A 12-week fellowship for founders in ${c} — mentors, grants, demos.`,
    desc: (c) =>
      `A cohort of 20 founders in ${c} moves from idea to shipped MVP with weekly mentor sessions, customer-development sprints, and a demo day where the top teams receive micro-grants and accelerator intros.`,
  };
  for (const country of ["India", "Nigeria", "Kenya", "Brazil", "Mexico", "Germany", "United Kingdom", "Canada", "Singapore", "United Arab Emirates", "Japan", "South Korea", "Australia", "France", "Netherlands", "Spain", "Italy", "Poland", "Sweden"]) {
    const city = CITIES[country][0];
    out.push(
      ...chapterVariants(
        { ...hubTemplate, country, title: (c) => `Young Founders Fellowship — ${country}` },
        [city],
      ),
    );
  }

  return out;
}

