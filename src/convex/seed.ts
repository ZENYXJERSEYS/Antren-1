// ─────────────────────────────────────────────────────────────────────────────
// Seed mutation — idempotent, safe to run on every deploy.
// ─────────────────────────────────────────────────────────────────────────────

export const seedOpportunities = mutation({
  args: {},
  handler: async (ctx) => {
    const existing = await ctx.db.query("opportunities").first();
    if (existing) {
      return { seeded: false, count: await ctx.db.query("opportunities").count() };
    }

    const now = Date.now();
    const DAY = 86_400_000;
    const docs = SEED.map((s, i) => {
      const deadline =
        s.deadlineDays === null ? now + 365 * DAY : now + s.deadlineDays * DAY;
      const verified = !s.unverified;
      const status =
        s.expired || (s.deadlineDays !== null && s.deadlineDays < 0)
          ? "expired"
          : "published";
      const lastVerifiedAt = s.recentlyVerified
        ? now - 2 * DAY
        : s.deadlineUpdated
          ? now - 5 * DAY
          : now - (3 + (i % 38)) * DAY;
      const verificationStatus = s.unverified
        ? "unverified"
        : status === "expired"
          ? "expired"
          : s.recentlyVerified
            ? "recently_verified"
            : s.deadlineUpdated
              ? "deadline_updated"
              : "verified";
      const short = s.short ?? s.desc?.slice(0, 140) ?? s.title;
      const desc =
        s.desc ??
        `${s.title} by ${s.provider} — ${s.eligibility}. Application details, eligibility, and deadlines are listed on the official page.`;
      const docsList = s.docs ?? ["Online application"];
      const method = s.method ?? "Online application via official portal";
      const url = s.url ?? `https://antren.app/program/${i}`;
      return {
        title: s.title,
        subtitle: s.subtitle,
        description: desc,
        shortDescription: short,
        provider: s.provider,
        officialUrl: url,
        category: s.category,
        subFields: s.subFields,
        location: s.location,
        country: s.country,
        remote: s.remote,
        eligibility: s.eligibility,
        gradeEligibility: s.grades,
        collegeOnly: s.grades.length === 1 && s.grades[0] === "college",
        cost: s.cost,
        isFree: s.cost === 0,
        currency: "USD",
        stipend: s.stipend,
        stipendText: s.stipendText,
        deadline,
        rollingDeadline: s.deadlineDays === null,
        duration: s.duration,
        applicationMethod: method,
        requiredDocuments: docsList,
        verificationStatus,
        lastVerifiedAt,
        verificationNote: verified
          ? "Reviewed against provider materials"
          : "Pending manual review",
        status,
        media: [
          {
            type: "cover",
            url: "",
            emoji: s.emoji,
            gradient: `linear-gradient(135deg, ${s.colors[0]}, ${s.colors[1]})`,
          },
        ],
        tags: s.tags,
        featured: s.featured ?? false,
        isNew: s.newBadge ?? i % 9 === 0,
        views: 120 + ((i * 977) % 8600),
        createdAt: now - (i % 90) * DAY,
        updatedAt: now - (i % 14) * DAY,
        searchText: [s.title, s.subtitle, s.provider, s.category, ...s.subFields, ...s.tags]
          .join(" ")
          .toLowerCase(),
      };
    });

    // Insert in batches of 200 for resilience
    for (let i = 0; i < docs.length; i += 200) {
      const batch = docs.slice(i, i + 200);
      await Promise.all(batch.map((d) => ctx.db.insert("opportunities", d)));
    }

    return { seeded: true, count: docs.length };
  },
});
